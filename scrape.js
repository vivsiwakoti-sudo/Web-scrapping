// Scrapes titles and prices of Young Adult (teen) books from books.toscrape.com,
// prints the five cheapest, and writes index.html.
const fs = require("fs");
const path = require("path");

const BASE = "https://books.toscrape.com/catalogue/category/books/young-adult_21/";

const decode = (s) =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");

const escapeHtml = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

async function scrapePage(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const html = await res.text();

  const books = [];
  for (const pod of html.split('<article class="product_pod">').slice(1)) {
    const title = pod.match(/<h3><a [^>]*title="([^"]*)"/);
    const price = pod.match(/<p class="price_color">[^\d]*([\d.]+)<\/p>/);
    if (title && price) books.push({ title: decode(title[1]), price: parseFloat(price[1]) });
  }
  const hasNext = /<li class="next">/.test(html);
  return { books, hasNext };
}

async function scrapeAll() {
  const all = [];
  for (let page = 1; ; page++) {
    const url = BASE + (page === 1 ? "index.html" : `page-${page}.html`);
    const { books, hasNext } = await scrapePage(url);
    all.push(...books);
    if (!hasNext) break;
  }
  return all;
}

function buildHtml(books, cheapest) {
  const row = (b, i) =>
    `        <tr><td>${i + 1}</td><td>${escapeHtml(b.title)}</td><td class="price">£${b.price.toFixed(2)}</td></tr>`;
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Best Books for Teenagers – Cheapest Picks</title>
  <style>
    body { font-family: system-ui, sans-serif; background: #f4f6fb; color: #222; margin: 0; padding: 2rem 1rem; }
    main { max-width: 800px; margin: 0 auto; }
    h1 { margin-bottom: .25rem; }
    .sub { color: #666; margin-top: 0; }
    section { background: #fff; border-radius: 10px; padding: 1rem 1.5rem; margin: 1.5rem 0; box-shadow: 0 1px 4px rgba(0,0,0,.1); }
    table { width: 100%; border-collapse: collapse; }
    th, td { text-align: left; padding: .5rem .6rem; border-bottom: 1px solid #eee; }
    th { background: #fafafa; }
    .price { text-align: right; font-weight: 600; white-space: nowrap; }
    th:last-child { text-align: right; }
    .top5 tr:first-child td { color: #0a7d32; }
    footer { color: #888; font-size: .85rem; text-align: center; }
  </style>
</head>
<body>
  <main>
    <h1>Best Books for Teenagers</h1>
    <p class="sub">Young Adult titles scraped from <a href="https://books.toscrape.com">books.toscrape.com</a> on ${new Date().toLocaleDateString("en-US")}</p>

    <section class="top5">
      <h2>5 Cheapest Books</h2>
      <table>
        <thead><tr><th>#</th><th>Title</th><th>Price</th></tr></thead>
        <tbody>
${cheapest.map(row).join("\n")}
        </tbody>
      </table>
    </section>

    <section>
      <h2>All ${books.length} Books</h2>
      <table>
        <thead><tr><th>#</th><th>Title</th><th>Price</th></tr></thead>
        <tbody>
${books.map(row).join("\n")}
        </tbody>
      </table>
    </section>
    <footer>Generated by scrape.js</footer>
  </main>
</body>
</html>
`;
}

(async () => {
  const books = await scrapeAll();
  const sorted = [...books].sort((a, b) => a.price - b.price || a.title.localeCompare(b.title));
  const cheapest = sorted.slice(0, 5);

  console.log(`Scraped ${books.length} books.\n`);
  console.log("Five cheapest books:");
  cheapest.forEach((b, i) => console.log(`${i + 1}. ${b.title} - £${b.price.toFixed(2)}`));

  const out = path.join(__dirname, "index.html");
  fs.writeFileSync(out, buildHtml(sorted, cheapest), "utf8");
  console.log(`\nWrote ${out}`);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
